import assert from 'node:assert/strict';
import {followSegment,WaypointTracker} from '../src/trajectory.js';
import {scanHazard} from '../src/avoidance.js';
import {CITY_BUILDINGS,withCity,cityBuildings} from '../src/city.js';
const mid=followSegment([0,0],[10,0],[4,1],{lookahead:1,speed:1.5});
assert.ok(Math.abs(mid.target[0]-5)<.01);
assert.ok(Math.abs(mid.target[1])<1e-6);
assert.ok(Math.abs(mid.crossTrack-1)<.01);
const end=followSegment([0,0],[10,0],[9.9,0],{lookahead:1});
assert.ok(end.remaining<.2 && end.target[0]<=10);
const stationary=followSegment([0,0],[0,0],[1,1]);
assert.equal(stationary.velocity[0],0);
const follower=new WaypointTracker();
assert.ok(follower.update(1,[[0,0,3],[10,0,3]],[4,1],2).target[0]>4);
const scan={angles:[-1.2,0,.5,2],ranges:[1.1,1.3,4,1.1],maxRange:25};
const blocked=scanHazard(scan,0,1.65);
assert.equal(blocked.blocked,true);
assert.ok(blocked.distance===1.3);
assert.equal(scanHazard({...scan,ranges:[25,25,25,25]},0).blocked,false);
assert.equal(CITY_BUILDINGS.length,cityBuildings().length);
assert.ok(CITY_BUILDINGS.length>=40);
const scene=withCity('<mujoco><worldbody></worldbody></mujoco>');
assert.equal((scene.match(/name="city_/g)||[]).length,CITY_BUILDINGS.length);
assert.ok(CITY_BUILDINGS.every(b=>Math.abs(b.x)>12||Math.abs(b.y)>12));
console.log('PASS: pure-pursuit trajectory, frontal scan obstacle detection, deterministic physical city');
